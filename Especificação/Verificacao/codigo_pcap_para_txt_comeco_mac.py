# Tipos de enlace
DLT_NULL = 0
DLT_EN10MB = 1


# Endereços MAC sintéticos para transformar DLT_NULL em Ethernet II
# O PCAP foi capturado usando DLT_NULL (LINKTYPE_NULL=0),
# formato utilizado em interfaces de loopback.
# Como esse formato não possui cabeçalho Ethernet com endereços MAC,
# criamos endereços MAC sintéticos para montar um quadro Ethernet II.
#
# 0x02 = 00000010:
# bit 0 = 0 -> endereço unicast
# bit 1 = 1 -> endereço localmente administrado
#
# Esses MACs são usados somente na simulação e não representam
# endereços físicos reais capturados no Wireshark.
DEST_MAC = bytes.fromhex("020000000002")
SOURCE_MAC = bytes.fromhex("020000000001")


